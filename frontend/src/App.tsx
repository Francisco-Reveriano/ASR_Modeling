              {!realtime && <><label className="field">Speech review<select value={settings?.astra_speech_mode || ''} disabled={speaking && !!session} onChange={event => setting('astra_speech_mode', event.target.value)}>{config?.speech_modes.map(mode => <option key={mode}>{mode}</option>)}</select></label><label className="inline-check"><input type="checkbox" checked={!!settings?.speaker_voices} disabled={speaking && !!session} onChange={event => setting('speaker_voices', event.target.checked)} /> Different voice per speaker</label></>}
