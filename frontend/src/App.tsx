  const selected = session && active ? session.settings : settings ? { ...settings, model_pair: inputModel! } : null;
  const exportFormats = session?.settings.model_pair === 'gpt-realtime-translate' ? ['txt', 'json'] : ['txt', 'json', 'csv', 'srt', 'vtt'];
  const inputStopped = session?.kind === 'microphone' ? session.input_finished : !!session?.stop_requested;
  const realtime = selected?.model_pair === 'gpt-realtime-translate';
  const speaking = session ? session.settings.speech_enabled : !!settings?.speech_enabled;
  const canCapture = typeof navigator !== 'undefined' && !!navigator.mediaDevices?.getUserMedia && !!window.AudioWorkletNode;

  useEffect(() => {
    const createCapture = () => new CaptureController({ onStatus: setCaptureState, onError: setError });
    capture.current = createCapture();
    speech.current = new SpeechController({ onStatus: setSpeechState, onAcknowledgement: value => acknowledgeRef.current({ type: 'speech.ack', ...value }) });
    return () => { capture.current?.dispose(); speech.current?.dispose(); capture.current = null; speech.current = null; };
  }, []);
  useEffect(() => {
    let cancelled = false;
    const recover = async () => {
      try {
        const value = await api.config();
        if (cancelled) return;
        setConfig(value); setSettings(value.defaults);
        setModelChoices({ microphone: value.defaults.model_pair, upload: value.defaults.model_pair });
        const id = restoringId.current;
        if (id) {
          try {
            const restored = await api.get(id);
            if (cancelled) return;
            restoringId.current = null;
            setSession(restored); setSettings(restored.settings); setTab(restored.kind);
            if (restored.kind !== 'evaluation') setModelChoices(current => ({ ...current, [restored.kind]: restored.settings.model_pair }));
            setNotice(restored.kind === 'microphone' && !restored.finished
              ? 'Your previous results are restored. Microphone capture was interrupted by the page reload; accepted audio will finish. Start a new conversation to record again.'
              : 'Your previous session is restored. Processing and available results are preserved.');
          } catch (failure) {
            if (cancelled) return;
            if (failure instanceof ApiError && failure.status === 404) { restoringId.current = null; updateSessionUrl(null); setNotice('The previous session expired or was cleared. Start a new conversation.'); }
            else setError(errorMessage(failure));
          }
        }
      } catch (failure) { if (!cancelled) setError(errorMessage(failure)); }
      finally { if (!cancelled) setLoading(false); }
    };
    void recover();
    return () => { cancelled = true; };
  }, []);
  useEffect(() => { if (!loading && (session || !restoringId.current)) updateSessionUrl(session?.id || null); }, [session?.id, loading]);
  useEffect(() => { commandGeneration.current += 1; setCommandPending(false); }, [session?.id]);
  useEffect(() => { try { localStorage.setItem(preferenceKey, JSON.stringify(preferences)); } catch { /* Preferences remain usable with browser storage blocked. */ } }, [preferences]);
  useEffect(() => {
    if (!file) { setFileUrl(''); return; }
    const url = URL.createObjectURL(file); setFileUrl(url);
    return () => URL.revokeObjectURL(url);
  }, [file]);
  useEffect(() => {
    let alive = true;
    const refresh = () => navigator.mediaDevices?.enumerateDevices?.().then(value => { if (alive) setDevices(value.filter(item => item.kind === 'audioinput')); }).catch(() => {});
    void refresh(); navigator.mediaDevices?.addEventListener?.('devicechange', refresh);
    return () => { alive = false; navigator.mediaDevices?.removeEventListener?.('devicechange', refresh); };
  }, []);
  useEffect(() => {
    const pending = replacement.current;
    if (!pending || session?.id !== pending.nextId) return;
    if (session.status === 'failed') {
      replacement.current = null; setSession(pending.previous);
      setError(session.error || 'The new session could not start. Your previous results are preserved.');
      void api.remove(pending.nextId).catch(() => {});
    } else if (session.status !== 'preparing' && (session.kind !== 'microphone' || captureState.phase === 'recording')) {
      replacement.current = null; void api.remove(pending.previous.id).catch(() => {});
    }
  }, [session, captureState.phase]);
  function setting<K extends keyof SessionSettings>(key: K, value: SessionSettings[K]) { setSettings(current => current ? { ...current, [key]: value } : current); }
  function preference<K extends keyof Preferences>(key: K, value: Preferences[K]) { setPreferences(current => ({ ...current, [key]: value })); }
