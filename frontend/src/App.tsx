import { useEffect, useRef, useState } from 'react';
import { api, ApiError, errorMessage } from './api';
import { CaptureController, SpeechController } from './audio';
import type { CaptureStatus, SpeechSnapshot, SpeechStatus } from './audio';
import Conversation, { Evaluation, Subtitles, timecode } from './Conversation';
import ReferencePanel from './ReferencePanel';
import type { ReferenceSelection } from './ReferencePanel';
import { isActive } from './session-state';
import { useSessionEvents } from './useSessionEvents';
import type { AppConfig, SessionCommand, SessionSettings, SessionSnapshot } from './types';

interface Preferences { original: boolean; subtitles: boolean; size: 'regular' | 'large' | 'largest'; position: 'top' | 'bottom' }
const preferenceDefaults: Preferences = { original: false, subtitles: true, size: 'large', position: 'top' };
const preferenceKey = 'speech-voice-presentation-v1';
function sessionFromUrl() {
  const value = new URL(location.href).searchParams.get('session');
  return value && /^[a-f0-9-]{32,36}$/i.test(value) ? value : null;
}
function updateSessionUrl(id: string | null) {
  const url = new URL(location.href);
  if (id) url.searchParams.set('session', id); else url.searchParams.delete('session');
  history.replaceState(null, '', `${url.pathname}${url.search}${url.hash}`);
}
function loadPreferences(): Preferences {
  try {
    const saved = JSON.parse(localStorage.getItem(preferenceKey) || '{}');
    return {
      original: typeof saved.original === 'boolean' ? saved.original : false,
      subtitles: typeof saved.subtitles === 'boolean' ? saved.subtitles : true,
      size: ['regular', 'large', 'largest'].includes(saved.size) ? saved.size : 'large',
      position: saved.position === 'bottom' ? 'bottom' : 'top',
    };
  } catch { return preferenceDefaults; }
}
const initialSpeech: SpeechStatus = { phase: 'idle', message: 'Text subtitles only', enabled: false, paused: false, blocked: false, countdownSeconds: null, model: null, voices: {} };
const initialCapture: CaptureStatus = { phase: 'idle', message: '', sampleRate: null };

function Brand() {
  return <a className="brand" href="#main" aria-label="Speech Voice, main workspace"><svg viewBox="0 0 32 32" fill="none" stroke="currentColor" strokeWidth="2.5" strokeLinecap="round" aria-hidden="true"><path d="M4 13v6M10 8v16M16 4v24M22 10v12M28 14v4" /></svg><strong>speech</strong><span>/ voice</span></a>;
}
function ModelReadiness({ config }: { config: AppConfig | null }) {
  if (!config) return <p className="hint">Connecting to the local server…</p>;
  const labels: Record<string, string> = { breeze: 'Breeze ASR', tencent: 'Tencent translation', nemotron: 'Nemotron speakers', openai: 'OpenAI services' };
  return <ul className="readiness-list">{Object.entries(config.models).map(([key, value]) => {
    const details = value && typeof value === 'object' && !Array.isArray(value) ? value : {};
    return <li key={key}><div><strong>{labels[key] || key}</strong><span>{typeof details.location === 'string' ? details.location : 'This computer'}</span></div><span className={details.available === false ? 'needs-setup' : ''}>{details.available === false ? 'Setup needed' : key === 'openai' ? 'Key configured' : 'Files detected'}</span></li>;
  })}</ul>;
}
function modelDisclosure(model: string, speech: boolean): string {
  const voice = speech ? ' Spoken English is generated by OpenAI.' : '';
  if (model === 'gpt-realtime-translate') return `Audio is sent to OpenAI for English and source captions. This mode does not use Astra, Tencent, terminology, or speaker detection.${voice}`;
  if (model === 'Breeze + OpenAI') return `Breeze recognizes speech on this computer. Transcript text and terminology are sent to OpenAI for translation and corrections; Tencent and speaker detection run locally.${voice}`;
  return `Audio is sent to OpenAI for transcription. Transcript text and terminology are sent to OpenAI for English translation and corrections. Tencent and speaker detection run locally.${voice}`;
}
