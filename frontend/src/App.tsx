  const [tab, setTab] = useState<'microphone' | 'upload' | 'evaluation'>('microphone');
  const [preferences, setPreferences] = useState(loadPreferences);
  const [error, setError] = useState('');
  const [notice, setNotice] = useState('');
  const [loading, setLoading] = useState(true);
  const [working, setWorking] = useState(false);
  const [commandPending, setCommandPending] = useState(false);
  const commandGeneration = useRef(0);
  const currentSessionId = useRef(session?.id);
  currentSessionId.current = session?.id;
  const [devices, setDevices] = useState<MediaDeviceInfo[]>([]);
  const [deviceId, setDeviceId] = useState('');
  const [file, setFile] = useState<File | null>(null);
  const [inputGeneration, setInputGeneration] = useState(0);
  const replacement = useRef<{ previous: SessionSnapshot; nextId: string } | null>(null);
  const restoringId = useRef(sessionFromUrl());
  const [fileUrl, setFileUrl] = useState('');
  const [reference, setReference] = useState<ReferenceSelection>({ file: null, options: { format: 'auto' }, ready: false });
  const [speechState, setSpeechState] = useState<SpeechStatus>(initialSpeech);
  const [captureState, setCaptureState] = useState<CaptureStatus>(initialCapture);
  const capture = useRef<CaptureController | null>(null);
  const speech = useRef<SpeechController | null>(null);
  const acknowledgeRef = useRef<(value: unknown) => void>(() => {});
  const { connection, acknowledge } = useSessionEvents(session?.id, setSession, value => speech.current?.update(value as SpeechSnapshot));
  acknowledgeRef.current = acknowledge;
