              {fileUrl && <audio controls preload="metadata" src={fileUrl} aria-label="Preview uploaded recording" />}
              {tab === 'evaluation' && <><p className="hint">Evaluation uses the local Breeze baseline. References are for comparison only.</p><ReferencePanel key={inputGeneration} disabled={frozen} onChange={setReference} /></>}
